#!/usr/bin/env node
// Original notices of the events, for the Details button of their cards in the Events tab and the Event Catalog (Events Part 1,
// Task 5; in the original game the Details of an event card opened the event's notice). Same model as make-raid-notices.js:
// reads the private notice texts under KHUX_RAID_SRC (raid_census/work/notice_text.json: {notice id: plain text of the SQUARE
// ENIX BRIDGE notice page}, never copied into the repo) and the notice ids of the event records (game_data/events.json of
// make-events.js, entry.noticeIds). Writes server/game_data/event_notices.json (git-ignored: the notice text is SQUARE ENIX's,
// it never goes in the public repo):
//   {note, rows: {censusId: {noticeIds}}, notices: {noticeId: {title, date, time, category, body: [lines]}}, missing: [{censusId, noticeId}],
//   scrubbed: [noticeId of the notices whose player ranking was removed]}
// The text is kept as it is, less the player rankings and the page boilerplate (make-raid-notices.js scrub; the page runs it
// again). server.js reads the file at request time (a new file is seen without a restart).
//
//   node server/make-event-notices.js      (after make-events.js; no master revision needed)
'use strict';
// tables of the original notices put back after the rankings are scrubbed (notice-tables.js, 14-11)
const tables = require('./notice-tables');

const fs = require('fs');
const path = require('path');
const { parseNotice, scrub } = require('./make-raid-notices');

const OUT = process.env.KHUX_EVENT_NOTICES_OUT || path.join(__dirname, 'game_data', 'event_notices.json');
const INDEX = process.env.KHUX_EVENT_INDEX || path.join(__dirname, 'game_data', 'events.json');
const DEFAULT_SRC = 'D:\\Progetto_Restauro_KH_UX\\private\\events\\sources';

// entries (events.json) + {id: text} -> the document written to OUT
function build({ entries, noticeText }) {
  const rows = {}, notices = {}, missing = [], scrubbed = [];
  for (const e of entries || []) {
    const ids = [];
    for (const id of e.noticeIds || []) {
      if (!(id in notices)) {
        const n = noticeText[id] === undefined ? null : parseNotice(noticeText[id]);
        if (n) { const s = scrub(n.body); n.body = tables.withTables(id, s.body).body; if (s.removed) scrubbed.push(id); }
        notices[id] = n;
      }
      if (notices[id]) ids.push(id); else missing.push({ censusId: e.censusId, noticeId: id });
    }
    if (ids.length) rows[e.censusId] = { noticeIds: ids };
  }
  for (const id of Object.keys(notices)) if (!notices[id]) delete notices[id];
  return { note: 'Generated by server/make-event-notices.js from the private notice texts: SQUARE ENIX text, git-ignored, never committed.',
    rows, notices, missing, scrubbed };
}

if (require.main === module) {
  const src = process.env.KHUX_RAID_SRC || DEFAULT_SRC;
  const entries = JSON.parse(fs.readFileSync(INDEX, 'utf8')).entries || [];
  const noticeText = JSON.parse(fs.readFileSync(path.join(src, 'raid_census', 'work', 'notice_text.json'), 'utf8'));
  const doc = build({ entries, noticeText });
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, JSON.stringify(doc));
  console.log(`event notices: ${Object.keys(doc.rows).length} of ${entries.length} events with a notice (${Object.keys(doc.notices).length} notices) -> ${OUT}`);
  if (doc.missing.length) console.log(`  not found: ${doc.missing.map((m) => `${m.censusId} (${m.noticeId})`).join(', ')}`);
  if (doc.scrubbed.length) console.log(`  player rankings removed from: ${doc.scrubbed.join(' ')}`);
}

module.exports = { build, OUT };
