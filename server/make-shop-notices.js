#!/usr/bin/env node
// Original notices of the Shop banners, for the Details page of every banner of the Banner Catalog (in the original game the
// Details of a deal and its notice told the player what the deal gave). Same pipeline as the raid notices (make-raid-notices.js):
// - server/shop_notice_map.tsv (versioned, ids only): banner rowId -> WW notice id, other notices naming it, confidence, note
//   (where the match comes from, or what was searched when no notice was found);
// - the private notice texts, never copied into the repo: KHUX_RAID_SRC raid_census/work/notice_text.json ({id: plain text of the
//   SQUARE ENIX BRIDGE notice page}, the 2,604 WW notices) and, for notices missing there, KHUX_SHOP_NOTICES_EXTRA (default
//   reference\shop_notices_extra\notice_text_extra.json: the same form, from the official pages fetched on 06-11).
// Writes server/game_data/shop_notices.json (git-ignored: the notice text is SQUARE ENIX's, it never goes in the public repo):
//   {note, rows: {rowId: {noticeId, alt: [noticeId], confidence, note}}, notices: {noticeId: {title, date, time, category,
//   body: [lines]}}, missing: {rowId: note}, scrubbed: [noticeId]}. KHUX_SHOP_NOTICES_OUT writes elsewhere (dry runs).
// The text is kept as it is (lines trimmed, empty lines dropped) less the page boilerplate and any player ranking
// (make-raid-notices.js scrub): the page (shop-notice-pages.js) lays it out without changing a sentence.
//
//   node server/make-shop-notices.js      (read at request time by the server: no master revision, no restart)
'use strict';

const fs = require('fs');
const path = require('path');
const { parseNotice, scrub } = require('./make-raid-notices');

const OUT = process.env.KHUX_SHOP_NOTICES_OUT || path.join(__dirname, 'game_data', 'shop_notices.json');
const MAP = process.env.KHUX_SHOP_NOTICE_MAP || path.join(__dirname, 'shop_notice_map.tsv');
const DEFAULT_SRC = 'D:\\Progetto_Restauro_KH_UX\\private\\events\\sources';
const DEFAULT_EXTRA = 'D:\\Progetto_Restauro_KH_UX\\reference\\shop_notices_extra\\notice_text_extra.json';

// shop_notice_map.tsv -> [{rowId, noticeId (number | null), alt: [number], confidence, note}] (# lines are comments)
function readMap(text) {
  const lines = String(text || '').split(/\r?\n/).filter((l) => l.trim() && !l.startsWith('#'));
  const head = (lines.shift() || '').split('\t');
  const col = (name) => head.indexOf(name);
  if (col('rowId') < 0 || col('noticeId') < 0) throw new Error('shop_notice_map.tsv: no rowId / noticeId header');
  const num = (s) => (/^\d+$/.test(String(s || '').trim()) ? Number(s) : null);
  return lines.map((l) => {
    const c = l.split('\t');
    return { rowId: c[col('rowId')], noticeId: num(c[col('noticeId')]), alt: String(c[col('alt')] || '').split(',').map(num).filter((n) => n !== null),
      confidence: c[col('confidence')] || '', note: c[col('note')] || '' };
  });
}

// map rows + {id: text} -> the document written to OUT. A row whose notice has no text goes to missing (with the reason).
function build({ map, noticeText }) {
  const parsed = new Map(), scrubbed = new Set();
  const notice = (id) => {
    if (!parsed.has(id)) {
      const n = noticeText[id] === undefined ? null : parseNotice(noticeText[id]);
      if (n) { const s = scrub(n.body); n.body = s.body; if (s.removed) scrubbed.add(id); }
      parsed.set(id, n);
    }
    return parsed.get(id);
  };
  const rows = {}, missing = {};
  for (const r of map) {
    if (r.noticeId !== null && notice(r.noticeId)) {
      rows[r.rowId] = { noticeId: r.noticeId, alt: r.alt.filter((n) => n !== r.noticeId && notice(n)), confidence: r.confidence, note: r.note };
    } else {
      missing[r.rowId] = r.noticeId !== null ? `${r.note ? `${r.note}; ` : ''}text of notice ${r.noticeId} not available` : r.note;
    }
  }
  const used = [...new Set(Object.values(rows).flatMap((r) => [r.noticeId, ...r.alt]))].sort((a, b) => a - b);
  return { note: 'Generated by server/make-shop-notices.js from the private notice texts: SQUARE ENIX text, git-ignored, never committed.',
    rows, notices: Object.fromEntries(used.map((n) => [n, notice(n)])), missing, scrubbed: used.filter((n) => scrubbed.has(n)) };
}

function buildFrom(src = DEFAULT_SRC, extra = DEFAULT_EXTRA, mapFile = MAP) {
  const noticeText = JSON.parse(fs.readFileSync(path.join(src, 'raid_census', 'work', 'notice_text.json'), 'utf8'));
  if (extra && fs.existsSync(extra)) {
    for (const [id, t] of Object.entries(JSON.parse(fs.readFileSync(extra, 'utf8')))) if (noticeText[id] === undefined) noticeText[id] = t;
  }
  return build({ map: readMap(fs.readFileSync(mapFile, 'utf8')), noticeText });
}

if (require.main === module) {
  const doc = buildFrom(process.env.KHUX_RAID_SRC || DEFAULT_SRC, process.env.KHUX_SHOP_NOTICES_EXTRA || DEFAULT_EXTRA);
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, JSON.stringify(doc));
  const rows = Object.values(doc.rows), count = (c) => rows.filter((r) => r.confidence === c).length;
  console.log(`shop notices: ${rows.length} banners with their original notice (${Object.keys(doc.notices).length} notices; high ${count('high')}, medium ${count('medium')}, low ${count('low')}), `
    + `${Object.keys(doc.missing).length} without -> ${OUT}`);
  console.log(`  without a notice: ${Object.keys(doc.missing).join(' ')}`);
  if (doc.scrubbed.length) console.log(`  player rankings removed from: ${doc.scrubbed.join(' ')}`);
}

module.exports = { readMap, build, buildFrom, OUT, MAP, DEFAULT_SRC, DEFAULT_EXTRA };
